"""Generate current master Xacro, MJCF and USD from the authoritative URDFs.

This is a scoped converter for the two existing master models, not a general
robot importer. No inertia, collision, actuator or physics constraint is added.
"""

import argparse
import copy
import math
import shutil
import struct
import tempfile
import xml.etree.ElementTree as ET
from pathlib import Path

import numpy as np
from _metadata import hash_tree, update_config
from pxr import Gf, Sdf, Usd, UsdGeom, Vt
from scipy.spatial.transform import Rotation

ASSETS = Path(__file__).resolve().parents[1] / "ros/taccap_master_description"
# The "tcp" site sits at the <side>_eef_link origin (config/master.json
# "tcp_link"), so it introduces no measurement of its own.
# Matches the slave's config/model.json units block; USD angles stay degrees.
MASTER_UNITS = {"length": "m", "angle": "rad", "mass": "kg"}
XACRO = "http://www.ros.org/wiki/xacro"
ET.register_namespace("xacro", XACRO)


def pose(origin):
    position = np.zeros(3)
    rotation = Rotation.identity()
    if origin is not None:
        position = np.fromstring(origin.get("xyz", "0 0 0"), sep=" ")
        rotation = Rotation.from_euler(
            "xyz", np.fromstring(origin.get("rpy", "0 0 0"), sep=" ")
        )
    return position, rotation


def numbers(values):
    return " ".join(f"{v:.16g}" for v in values)


def mj_pose(origin):
    position, rotation = pose(origin)
    return {"pos": numbers(position), "quat": numbers(rotation.as_quat()[[3, 0, 1, 2]])}


def write_xml(path, root):
    root.insert(
        0,
        ET.Comment(
            " Generated by scripts/generate_master_models.py; edit source URDF. Visual/kinematic only. "
        ),
    )
    ET.indent(root, space="  ")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(ET.tostring(root, encoding="unicode") + "\n")


def make_xacro(urdf, side, output):
    root = ET.Element("robot")
    macro = ET.SubElement(
        root,
        f"{{{XACRO}}}macro",
        name=f"taccap_master_{side}",
        params="prefix:='' mesh_root:='package://taccap_master_description/meshes'",
    )
    for source in urdf:
        element = copy.deepcopy(source)
        for node in element.iter():
            for attribute in ("name", "link", "joint"):
                if attribute in node.attrib:
                    node.set(attribute, "${prefix}" + node.get(attribute))
            if node.tag == "mesh":
                node.set(
                    "filename",
                    "${mesh_root}/" + side + "/" + Path(node.get("filename")).name,
                )
        macro.append(element)
    write_xml(output / "urdf" / f"taccap_g1_master_{side}.urdf.xacro", root)


def new_stage(path):
    path.parent.mkdir(parents=True, exist_ok=True)
    stage = Usd.Stage.CreateNew(str(path))
    stage.SetDefaultPrim(UsdGeom.Xform.Define(stage, "/Master").GetPrim())
    UsdGeom.SetStageUpAxis(stage, "Z")
    UsdGeom.SetStageMetersPerUnit(stage, 1)
    stage.GetRootLayer().documentation = (
        "Generated TacCap master visual asset; no rigid-body physics."
    )
    return stage


def usd_transform(xform, origin):
    position, rotation = pose(origin)
    xform.AddTranslateOp().Set(Gf.Vec3d(*position))
    x, y, z, w = rotation.as_quat()
    xform.AddOrientOp().Set(Gf.Quatf(float(w), Gf.Vec3f(float(x), float(y), float(z))))


def usd_meshes(output, side):
    for source in sorted((ASSETS / "meshes" / side).glob("*.STL")):
        data = source.read_bytes()
        count = struct.unpack_from("<I", data, 80)[0]
        if len(data) != 84 + 50 * count:
            raise ValueError(f"Expected binary STL: {source}")
        triangles = np.frombuffer(
            data,
            offset=84,
            dtype=np.dtype(
                [("normal", "<f4", 3), ("vertices", "<f4", (3, 3)), ("attr", "<u2")]
            ),
        )
        points = triangles["vertices"].reshape(-1, 3).copy()
        stage = new_stage(output / "usd/meshes" / side / f"{source.stem}.usdc")
        mesh = UsdGeom.Mesh.Define(stage, "/Master/Mesh")
        mesh.CreatePointsAttr(Vt.Vec3fArray.FromNumpy(points))
        mesh.CreateFaceVertexCountsAttr(
            Vt.IntArray.FromNumpy(np.full(count, 3, np.int32))
        )
        mesh.CreateFaceVertexIndicesAttr(
            Vt.IntArray.FromNumpy(np.arange(count * 3, dtype=np.int32))
        )
        mesh.CreateNormalsAttr(Vt.Vec3fArray.FromNumpy(triangles["normal"].copy()))
        mesh.SetNormalsInterpolation("uniform")
        mesh.CreateSubdivisionSchemeAttr("none")
        mesh.CreateExtentAttr(
            Vt.Vec3fArray.FromNumpy(np.array([points.min(0), points.max(0)]))
        )
        stage.GetRootLayer().Save()


def generate_side(output, side):
    urdf = ET.parse(ASSETS / "urdf" / f"taccap_g1_master_{side}.urdf").getroot()
    joints = {joint.find("child").get("link"): joint for joint in urdf.findall("joint")}
    tcp_link = f"{side}_eef_link"
    # (driver, follower): the URDF -Y finger drives, the +Y finger mimics it.
    fingers = (f"{side}_right_link", f"{side}_left_link")
    if urdf.find(f"link[@name='{tcp_link}']") is None:
        raise ValueError(f"Expected master TCP link {tcp_link}")
    signs = []
    # Both fingers share one principal hinge axis; set_opening and the USD
    # animation rotate about it from each finger's closed pose.
    axis = np.fromstring(joints[fingers[0]].find("axis").get("xyz"), sep=" ")
    if sorted(np.abs(axis)) != [0, 0, 1]:
        raise ValueError("Expected a principal master finger hinge axis")
    axis_name = "XYZ"[int(np.argmax(np.abs(axis)))]
    for link in fingers:
        joint = joints[link]
        if not np.array_equal(np.fromstring(joint.find("axis").get("xyz"), sep=" "), axis):
            raise ValueError("Expected both master fingers on the same hinge axis")
        mimic = joint.find("mimic")
        if mimic is not None and (
            mimic.get("joint") != joints[fingers[0]].get("name")
            or float(mimic.get("offset", "0")) != 0
        ):
            raise ValueError("Expected zero-offset mimic of the driving finger")
        # Signed rotation about the positive principal axis per unit opening.
        multiplier = float(mimic.get("multiplier", "1")) if mimic is not None else 1
        signs.append(multiplier * axis.sum())
    limit = float(joints[fingers[0]].find("limit").get("upper"))
    if float(joints[fingers[0]].find("limit").get("lower")) != 0:
        raise ValueError("Expected zero closed position")
    usd_meshes(output, side)

    def world(name):
        """Closed-pose world transform; the URDF root is the world frame."""
        joint = joints.get(name)
        if joint is None:
            return np.zeros(3), Rotation.identity()
        position, rotation = world(joint.find("parent").get("link"))
        offset, local = pose(joint.find("origin"))
        return position + rotation.apply(offset), rotation * local

    def usd_path(name):
        joint = joints.get(name)
        if joint is None:
            return f"/Master/{name}"
        return usd_path(joint.find("parent").get("link")) + "/" + name

    model = ET.Element("mujoco", model=f"taccap_master_{side}_kinematic")
    ET.SubElement(
        model, "compiler", angle="radian", fusestatic="false", discardvisual="false"
    )
    ET.SubElement(model, "option", gravity="0 0 0")
    assets = ET.SubElement(model, "asset")
    custom = ET.SubElement(model, "custom")
    ET.SubElement(custom, "numeric", name="master_opening_limit", data=str(limit))
    ET.SubElement(custom, "numeric", name="master_finger_signs", data=numbers(signs))
    ET.SubElement(custom, "numeric", name="master_finger_axis", data=numbers(np.abs(axis)))
    world_body = ET.SubElement(model, "worldbody")
    stage = new_stage(output / "usd" / f"{side}.usda")
    colors = {}
    for material in urdf.findall("material"):
        rgba = material.find("color").get("rgba")
        colors[material.get("name")] = np.fromstring(rgba, sep=" ")[:3]
        ET.SubElement(assets, "material", name=material.get("name"), rgba=rgba)
    mpos, mquat = [], []
    for link in urdf.findall("link"):
        name = link.get("name")
        source_joint = joints.get(name)
        origin = source_joint.find("origin") if source_joint is not None else None
        position, rotation = world(name)
        quaternion = rotation.as_quat()[[3, 0, 1, 2]]
        # Mocap bodies are world children; their closed pose is the body default.
        body = ET.SubElement(
            world_body,
            "body",
            name=name,
            mocap="true",
            pos=numbers(position),
            quat=numbers(quaternion),
        )
        if name == tcp_link:
            # Display group 3: hidden until toggled in the viewer.
            ET.SubElement(
                body,
                "site",
                name="tcp",
                pos="0 0 0",
                size="0.004",
                type="sphere",
                rgba="1 0.35 0 0.8",
                group="3",
            )
        mpos.extend(position)
        if name in fingers:
            angle = signs[fingers.index(name)] * limit
            rotation = rotation * Rotation.from_rotvec(np.abs(axis) * angle)
        mquat.extend(rotation.as_quat()[[3, 0, 1, 2]])
        path = usd_path(name)
        xform = UsdGeom.Xform.Define(stage, path)
        usd_transform(xform, origin)
        if name in fingers:
            getattr(xform, f"AddRotate{axis_name}Op")(opSuffix="opening").Set(0)
        for index, visual in enumerate(link.findall("visual")):
            filename = Path(visual.find("geometry/mesh").get("filename")).name
            mesh_name = Path(filename).stem
            geom_name = visual.get("name") or f"{name}_visual"
            ET.SubElement(
                assets, "mesh", name=mesh_name, file=f"../meshes/{side}/{filename}"
            )
            ET.SubElement(
                body,
                "geom",
                name=geom_name,
                type="mesh",
                mesh=mesh_name,
                material=visual.find("material").get("name"),
                mass="0",
                contype="0",
                conaffinity="0",
                group="1",
                **mj_pose(visual.find("origin")),
            )
            mesh = UsdGeom.Mesh.Define(stage, path + "/" + (visual.get("name") or "visual"))
            mesh.GetPrim().GetReferences().AddReference(
                f"./meshes/{side}/{mesh_name}.usdc", "/Master/Mesh"
            )
            usd_transform(mesh, visual.find("origin"))
            mesh.CreateDisplayColorAttr(
                [Gf.Vec3f(*colors[visual.find("material").get("name")])]
            )
    ET.SubElement(
        ET.SubElement(model, "keyframe"),
        "key",
        name="open",
        mpos=numbers(mpos),
        mquat=numbers(mquat),
    )
    write_xml(output / "mjcf" / f"{side}.xml", model)
    stage.GetRootLayer().Save()
    animation = new_stage(output / "usd" / f"{side}_open_close.usda")
    animation.GetDefaultPrim().GetReferences().AddReference(f"./{side}.usda")
    animation.SetTimeCodesPerSecond(60)
    animation.SetFramesPerSecond(60)
    animation.SetStartTimeCode(0)
    animation.SetEndTimeCode(120)
    for finger, sign in zip(fingers, signs):
        attribute = animation.GetPrimAtPath(usd_path(finger)).GetAttribute(
            f"xformOp:rotate{axis_name}:opening"
        )
        for time, value in ((0, 0), (60, math.degrees(sign * limit)), (120, 0)):
            attribute.Set(value, time)
    animation.GetRootLayer().Save()


def usd_metadata():
    """Mirror this generator's conversion settings into the package config file."""
    return {
        "generator": "scripts/generate_master_models.py",
        "entry_points": ["usd/left.usda", "usd/right.usda"],
        "animation_entry_points": [
            "usd/left_open_close.usda",
            "usd/right_open_close.usda",
        ],
        "default_prim": "/Master",
        "up_axis": "Z",
        "linear_unit": "m",
        "angular_unit": "degree",
        "physics_schemas": [],
        "animation": {
            "frames_per_second": 60,
            "start_time_code": 0,
            "end_time_code": 120,
            "keyframes": [0, 60, 120],
            "cycle": "closed -> open -> closed",
            "mechanism": "xformOp:rotateX on the right/left finger links (URDF hinge axis); no articulation or "
            "mimic constraint is authored",
        },
        "mesh_conversion": "Binary .usdc converted from each side's source STL "
        "without changing vertices; both entry points share one mesh layer set",
        "shipped_layers_sha256": hash_tree(ASSETS, "usd"),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--urdf-only", action="store_true", help="Generate only the master Xacro; leave MJCF/USD untouched")
    args = parser.parse_args()
    with tempfile.TemporaryDirectory(prefix="master-models-") as temporary:
        output = Path(temporary)
        for side in ("left", "right"):
            current = ET.parse(ASSETS / "urdf" / f"taccap_g1_master_{side}.urdf").getroot()
            make_xacro(current, side, output)
            if not args.urdf_only:
                generate_side(output, side)
        for source in sorted(p for p in output.rglob("*") if p.is_file()):
            target = ASSETS / source.relative_to(output)
            if args.check:
                if not target.is_file():
                    raise SystemExit(f"Missing generated asset: {target}")
                same = (
                    Sdf.Layer.FindOrOpen(str(source)).ExportToString()
                    == Sdf.Layer.FindOrOpen(str(target)).ExportToString()
                    if source.suffix in (".usda", ".usdc")
                    else source.read_bytes() == target.read_bytes()
                )
                if not same:
                    raise SystemExit(f"Stale generated asset: {target}")
            else:
                target.parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(source, target)
            print(target.relative_to(ASSETS))
    if args.urdf_only:
        return
    config = ASSETS / "config" / "master.json"
    # Hash the shipped layers, so this runs after the copy above.
    update_config(config, "units", MASTER_UNITS, args.check)
    update_config(config, "usd", usd_metadata(), args.check)
    print(config.relative_to(ASSETS))


if __name__ == "__main__":
    main()
