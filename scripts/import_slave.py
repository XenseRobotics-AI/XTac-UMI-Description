"""Adapt the hash-locked upstream slave URDF snapshot to this package.

The source snapshot is an immutable subset of the upstream asset directory
(``SNAPSHOT_PREFIXES``). Only root names/attachment, motor effort and Xacro
parameterization differ locally; physical properties are copied verbatim.
"""

import argparse
import copy
import hashlib
import json
import subprocess
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
VENDOR = ROOT / "vendor/taccap_slave"
SOURCE = VENDOR / "source"
ASSETS = ROOT / "ros/taccap_description"
XACRO = "http://www.ros.org/wiki/xacro"
# Upstream authoring records, screenshots and generator configs stay upstream.
SNAPSHOT_PREFIXES = ("LICENSES/", "NOTICE.md", "meshes/", "urdf/")
ET.register_namespace("xacro", XACRO)


def source_hashes():
    return {
        p.relative_to(SOURCE).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest()
        for p in sorted(SOURCE.rglob("*")) if p.is_file()
    }


def adapted_urdf(with_mount):
    suffix = "_with_mount" if with_mount else ""
    root = ET.parse(SOURCE / f"urdf/taccap_g1_slave{suffix}.urdf").getroot()
    if with_mount:
        root.find("link[@name='flange_link']").set("name", "taccap_mount_link")
        joint = root.find("joint[@name='flange_to_base_joint']")
        joint.set("name", "taccap_mount_joint")
        joint.find("parent").set("link", "taccap_mount_link")
    else:
        root.remove(root.find("link[@name='flange_link']"))
        root.remove(root.find("joint[@name='flange_to_base_joint']"))
    for limit in root.findall("joint[@type='revolute']/limit"):
        limit.set("effort", "1.1")
    return root


def macro_text():
    root = ET.Element("robot")
    root.append(ET.Comment(" Generated by scripts/import_slave.py from the locked upstream snapshot. "))
    macro = ET.SubElement(root, f"{{{XACRO}}}macro", name="taccap_g1_slave",
                          params="prefix:='' with_mount:=false mesh_root:='package://taccap_description/meshes'")
    mounted = adapted_urdf(True)
    for element in mounted:
        element = copy.deepcopy(element)
        optional = element.get("name") in ("taccap_mount_link", "taccap_mount_joint")
        for node in element.iter():
            for attribute in ("name", "link", "joint"):
                if attribute in node.attrib:
                    node.set(attribute, "${prefix}" + node.get(attribute))
            if node.tag == "mesh":
                relative = Path(node.get("filename")).relative_to("../meshes")
                node.set("filename", "${mesh_root}/" + relative.as_posix())
        if optional:
            ET.SubElement(macro, f"{{{XACRO}}}if", value="${with_mount}").append(element)
        else:
            macro.append(element)
    ET.indent(root, space="  ")
    return ET.tostring(root, encoding="unicode") + "\n"


def pin_commit(lock, repository, revision):
    """Only attribute this snapshot to a commit containing identical bytes."""
    prefix = f"{lock['path']}/"
    commit = subprocess.check_output(
        ["git", "-C", str(repository), "rev-parse", f"{revision}^{{commit}}"], text=True
    ).strip()
    listing = subprocess.check_output(
        ["git", "-C", str(repository), "ls-tree", "-r", "--name-only", commit, "--", lock["path"]], text=True
    ).splitlines()
    listing = {p for p in listing if p[len(prefix):].startswith(SNAPSHOT_PREFIXES)}
    expected = {prefix + p for p in lock["files_sha256"]}
    if listing != expected:
        raise SystemExit("Commit file set differs from the locked snapshot")
    for relative, digest in lock["files_sha256"].items():
        data = subprocess.check_output(
            ["git", "-C", str(repository), "show", f"{commit}:{lock['path']}/{relative}"]
        )
        if hashlib.sha256(data).hexdigest() != digest:
            raise SystemExit(f"Commit differs from snapshot: {relative}")
    lock["revision"] = commit
    lock["verification"] = "Every source file matches the pinned commit byte for byte."
    (VENDOR / "upstream.json").write_text(json.dumps(lock, indent=2, ensure_ascii=False) + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--pin-commit", help="Verify and record a subsequently published upstream commit")
    parser.add_argument("--source-repo", type=Path, help="Read-only local Git repository used to verify --pin-commit")
    args = parser.parse_args()
    lock = json.loads((VENDOR / "upstream.json").read_text())
    if source_hashes() != lock["files_sha256"]:
        raise SystemExit("Upstream snapshot differs from its lock; review the source update first")
    if args.pin_commit:
        if args.check or not args.source_repo:
            parser.error("--pin-commit requires --source-repo and cannot be used with --check")
        pin_commit(lock, args.source_repo, args.pin_commit)
    outputs = {
        ASSETS / "urdf/taccap_g1_slave_macro.xacro": macro_text().encode(),
        ASSETS / "config/upstream.json": (VENDOR / "upstream.json").read_bytes(),
    }
    for path in (SOURCE / "meshes").rglob("*"):
        if path.is_file():
            outputs[ASSETS / path.relative_to(SOURCE)] = path.read_bytes()
    expected_meshes = {p for p in outputs if p.is_relative_to(ASSETS / "meshes")}
    stale_meshes = {p for p in (ASSETS / "meshes").rglob("*") if p.is_file()} - expected_meshes
    if args.check and stale_meshes:
        raise SystemExit(f"Stale meshes: {sorted(stale_meshes)}")
    for path, data in outputs.items():
        if args.check:
            if not path.is_file() or path.read_bytes() != data:
                raise SystemExit(f"Regenerate imported asset: {path.relative_to(ROOT)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    if not args.check:
        for path in stale_meshes:
            path.unlink()
    print(f"Upstream snapshot and {len(outputs)} adapted files {'verified' if args.check else 'imported'}")


if __name__ == "__main__":
    main()
