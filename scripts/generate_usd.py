"""Generate fixed-base TacCap USD assets from the checked-in URDFs.

Scoped to this mesh-only model. Run generate_models.py first. OpenUSD can
author the documented PhysX mimic schema without installing Isaac Sim;
only a PhysX runtime can execute that constraint.
"""

import argparse
import math
import shutil
import struct
import tempfile
import xml.etree.ElementTree as ET
from pathlib import Path

import numpy as np
from _metadata import hash_tree, update_config
from pxr import Gf, Sdf, Usd, UsdGeom, UsdPhysics, Vt
from scipy.spatial.transform import Rotation

ASSETS = Path(__file__).resolve().parents[1] / "ros" / "taccap_description"
ROOT = "/TacCap"
MODEL = "taccap_g1_slave"
# Rigid body that carries massless EEF and camera reference frames.
BASE = "taccap_base_link"


def vector(text):
    return np.array([float(v) for v in text.split()])


def transform(origin):
    matrix = np.eye(4)
    if origin is not None:
        matrix[:3, 3] = vector(origin.get("xyz", "0 0 0"))
        matrix[:3, :3] = Rotation.from_euler(
            "xyz", vector(origin.get("rpy", "0 0 0"))
        ).as_matrix()
    # Drop ~1e-16 residue of the pi/2 flange rotation; "+ 0.0" clears -0.0.
    return matrix.round(15) + 0.0


def quat(matrix):
    x, y, z, w = Rotation.from_matrix(matrix).as_quat()
    return Gf.Quatf(float(w), Gf.Vec3f(float(x), float(y), float(z)))


def new_stage(path):
    stage = Usd.Stage.CreateNew(str(path))
    root = UsdGeom.Xform.Define(stage, ROOT)
    stage.SetDefaultPrim(root.GetPrim())
    UsdGeom.SetStageUpAxis(stage, UsdGeom.Tokens.z)
    UsdGeom.SetStageMetersPerUnit(stage, 1)
    UsdPhysics.SetStageKilogramsPerUnit(stage, 1)
    stage.GetRootLayer().documentation = "Generated by scripts/generate_usd.py."
    return stage


def generate_meshes(output):
    (output / "meshes").mkdir(parents=True)
    for source in sorted(p for p in (ASSETS / "meshes").rglob("*") if p.suffix.lower() == ".stl"):
        data = source.read_bytes()
        count = struct.unpack_from("<I", data, 80)[0]
        if len(data) != 84 + count * 50:
            raise ValueError(f"Expected binary STL: {source}")
        triangles = np.frombuffer(
            data,
            dtype=np.dtype(
                [("normal", "<f4", 3), ("vertices", "<f4", (3, 3)), ("attr", "<u2")]
            ),
            offset=84,
            count=count,
        )
        points = triangles["vertices"].reshape(-1, 3).copy()
        target = output / "meshes" / source.relative_to(ASSETS / "meshes").with_suffix(".usdc")
        target.parent.mkdir(parents=True, exist_ok=True)
        stage = new_stage(target)
        mesh = UsdGeom.Mesh.Define(stage, ROOT + "/Mesh")
        mesh.CreatePointsAttr(Vt.Vec3fArray.FromNumpy(points))
        mesh.CreateFaceVertexCountsAttr(
            Vt.IntArray.FromNumpy(np.full(count, 3, np.int32))
        )
        mesh.CreateFaceVertexIndicesAttr(
            Vt.IntArray.FromNumpy(np.arange(count * 3, dtype=np.int32))
        )
        mesh.CreateNormalsAttr(Vt.Vec3fArray.FromNumpy(triangles["normal"].copy()))
        mesh.SetNormalsInterpolation(UsdGeom.Tokens.uniform)
        mesh.CreateSubdivisionSchemeAttr(UsdGeom.Tokens.none)
        mesh.CreateExtentAttr(
            [
                Gf.Vec3f(*points.min(axis=0).tolist()),
                Gf.Vec3f(*points.max(axis=0).tolist()),
            ]
        )
        stage.GetRootLayer().Save()


def generate_model(output, with_mount):
    suffix = "_with_mount" if with_mount else ""
    urdf = ET.parse(ASSETS / "urdf" / f"{MODEL}{suffix}.urdf").getroot()
    simulation = ET.parse(ASSETS / "config" / "mujoco.xml").getroot()
    links = {link.get("name"): link for link in urdf.findall("link")}
    parents = {
        joint.find("child").get("link"): joint for joint in urdf.findall("joint")
    }

    def world_pose(name):
        joint = parents.get(name)
        if joint is None:
            return np.eye(4)
        return world_pose(joint.find("parent").get("link")) @ transform(
            joint.find("origin")
        )

    # Physical parts retain their own mass/inertia. Virtual frames follow the base.
    paths = {
        name: f"{ROOT}/{name}"
        if link.find("inertial") is not None
        else f"{ROOT}/{BASE}/{name}"
        for name, link in links.items()
    }
    stage = new_stage(output / f"{MODEL}{suffix}.usda")
    colors = {
        mat.get("name"): vector(mat.find("color").get("rgba"))[:3]
        for mat in urdf.findall("material")
    }
    for name, link in links.items():
        body = UsdGeom.Xform.Define(stage, paths[name])
        pose = world_pose(name)
        inertial = link.find("inertial")
        if inertial is None:
            pose = np.linalg.inv(world_pose(BASE)) @ pose
        body.AddTransformOp().Set(Gf.Matrix4d(pose.T.tolist()))
        if inertial is not None:
            UsdPhysics.RigidBodyAPI.Apply(body.GetPrim())
            mass = UsdPhysics.MassAPI.Apply(body.GetPrim())
            mass.CreateMassAttr(float(inertial.find("mass").get("value")))
            frame = transform(inertial.find("origin"))
            mass.CreateCenterOfMassAttr(Gf.Vec3f(*frame[:3, 3]))
            values = inertial.find("inertia").attrib
            tensor = np.array(
                [
                    [float(values["i" + "".join(sorted(a + b))]) for b in "xyz"]
                    for a in "xyz"
                ]
            )
            tensor = frame[:3, :3] @ tensor @ frame[:3, :3].T
            diagonal, axes = np.linalg.eigh(tensor)
            if np.linalg.det(axes) < 0:
                axes[:, 0] *= -1
            mass.CreateDiagonalInertiaAttr(Gf.Vec3f(*diagonal))
            mass.CreatePrincipalAxesAttr(quat(axes))
        for kind in ("visual", "collision"):
            for geometry in link.findall(kind):
                path = paths[name] + "/" + geometry.get("name")
                mesh = UsdGeom.Mesh.Define(stage, path)
                filename = Path(geometry.find("geometry/mesh").get("filename"))
                mesh.GetPrim().GetReferences().AddReference(
                    "./meshes/" + filename.relative_to("../meshes").with_suffix(".usdc").as_posix(), ROOT + "/Mesh"
                )
                mesh.AddTransformOp().Set(
                    Gf.Matrix4d(transform(geometry.find("origin")).T.tolist())
                )
                if kind == "visual":
                    mesh.CreateDisplayColorAttr(
                        [Gf.Vec3f(*colors[geometry.find("material").get("name")])]
                    )
                else:
                    mesh.CreatePurposeAttr(UsdGeom.Tokens.guide)
                    UsdPhysics.CollisionAPI.Apply(mesh.GetPrim())
                    UsdPhysics.MeshCollisionAPI.Apply(
                        mesh.GetPrim()
                    ).CreateApproximationAttr("convexHull")

    anchor = UsdPhysics.FixedJoint.Define(stage, ROOT + "/joints/root_fixed_joint")
    anchor.CreateBody1Rel().SetTargets([paths[BASE]])
    # The stage origin is the URDF root (mount face when mounted).
    anchor.CreateLocalPos0Attr(Gf.Vec3f(*world_pose(BASE)[:3, 3]))
    anchor.CreateLocalRot0Attr(quat(world_pose(BASE)[:3, :3]))
    UsdPhysics.ArticulationRootAPI.Apply(anchor.GetPrim())
    physical_joints = dict(parents)
    if with_mount:
        root_joint = ET.Element("joint", name="mount_to_base_fixed", type="fixed")
        ET.SubElement(root_joint, "parent", link=BASE)
        physical_joints["taccap_mount_link"] = root_joint
    for child, source in physical_joints.items():
        if links[child].find("inertial") is None or child == BASE:
            continue  # Virtual frames are already fixed Xforms on the base.
        path = ROOT + "/joints/" + source.get("name")
        revolute = source.get("type") == "revolute"
        joint = (
            UsdPhysics.RevoluteJoint if revolute else UsdPhysics.FixedJoint
        ).Define(stage, path)
        parent = source.find("parent").get("link")
        joint.CreateBody0Rel().SetTargets([paths[parent]])
        joint.CreateBody1Rel().SetTargets([paths[child]])
        pose = transform(source.find("origin"))
        if child == "taccap_mount_link":
            # Root adapter is physical; connect it to the anchored base body.
            joint.CreateBody0Rel().SetTargets([paths[BASE]])
            pose = np.linalg.inv(world_pose(BASE)) @ world_pose(child)
        joint.CreateLocalPos0Attr(Gf.Vec3f(*pose[:3, 3]))
        # USD revolute joints and the rotZ mimic use the joint-frame Z axis;
        # rotate BOTH joint frames so that Z lies along the signed URDF axis.
        axis_frame = np.eye(3)
        if revolute:
            axis = vector(source.find("axis").get("xyz"))
            if sorted(np.abs(axis)) != [0, 0, 1]:
                raise ValueError("Only principal TacCap joint axes are supported")
            if not np.array_equal(axis, [0, 0, 1]):
                # Rotate Z onto the axis (half-turn about the bisector for -Z).
                bisector = np.array([0.0, 0.0, 1.0]) + axis
                if not bisector.any():
                    bisector = np.array([1.0, 0.0, 0.0])
                bisector /= np.linalg.norm(bisector)
                axis_frame = Rotation.from_rotvec(np.pi * bisector).as_matrix().round(15) + 0.0
        joint.CreateLocalRot0Attr(quat(pose[:3, :3] @ axis_frame))
        joint.CreateLocalRot1Attr(quat(axis_frame))
        joint.CreateCollisionEnabledAttr(False)
        if not revolute:
            continue
        joint.CreateAxisAttr("Z")
        limit = source.find("limit")
        joint.CreateLowerLimitAttr(math.degrees(float(limit.get("lower"))))
        joint.CreateUpperLimitAttr(math.degrees(float(limit.get("upper"))))
        mimic = source.find("mimic")
        if mimic is not None:
            # PhysX equation: q + gearing * q_reference + offset = 0.
            prim = joint.GetPrim()
            prim.AddAppliedSchema("PhysxMimicJointAPI:rotZ")
            prefix = "physxMimicJoint:rotZ:"
            prim.CreateRelationship(prefix + "referenceJoint", custom=False).SetTargets(
                [ROOT + "/joints/" + mimic.get("joint")]
            )
            for key, value in (
                ("gearing", -float(mimic.get("multiplier", "1"))),
                ("offset", -math.degrees(float(mimic.get("offset", "0")))),
            ):
                prim.CreateAttribute(
                    prefix + key, Sdf.ValueTypeNames.Float, custom=False
                ).Set(value)
            prim.CreateAttribute(
                prefix + "referenceJointAxis", Sdf.ValueTypeNames.Token, custom=False
            ).Set("rotZ")
        else:
            settings = simulation.find(
                f"actuator/position[@joint='{source.get('name')}']"
            )
            drive = UsdPhysics.DriveAPI.Apply(joint.GetPrim(), "angular")
            drive.CreateTypeAttr("force")
            drive.CreateTargetPositionAttr(0)
            drive.CreateStiffnessAttr(float(settings.get("kp")) * math.pi / 180)
            drive.CreateDampingAttr(float(settings.get("kv")) * math.pi / 180)
            drive.CreateMaxForceAttr(float(limit.get("effort")))
    for pair in simulation.findall("contact/exclude"):
        UsdPhysics.FilteredPairsAPI.Apply(
            stage.GetPrimAtPath(paths[pair.get("body1")])
        ).CreateFilteredPairsRel().AddTarget(paths[pair.get("body2")])
    stage.GetRootLayer().Save()


def usd_metadata():
    """Mirror this generator's conversion settings into the package config file."""
    simulation = ET.parse(ASSETS / "config" / "mujoco.xml").getroot()
    urdf = ET.parse(ASSETS / "urdf" / f"{MODEL}.urdf").getroot()
    driven = urdf.find("joint[@name='taccap_right_finger_joint']")
    follower = urdf.find("joint[@name='taccap_left_finger_joint']").find("mimic")
    position = simulation.find("actuator/position[@joint='taccap_right_finger_joint']")
    limit = driven.find("limit")
    return {
        "generator": "scripts/generate_usd.py",
        "entry_points": [
            f"usd/{MODEL}.usda",
            f"usd/{MODEL}_with_mount.usda",
        ],
        "default_prim": ROOT,
        "up_axis": "Z",
        "linear_unit": "m",
        "mass_unit": "kg",
        "angular_unit": "degree",
        "collider_approximation": "convexHull",
        "collision_from_visuals": False,
        "merge_fixed_joints": False,
        "articulation": {
            "fixed_base": True,
            "anchor_joint": "joints/root_fixed_joint",
            "driven_joint": driven.get("name"),
            "mimic_schema": "PhysxMimicJointAPI:rotZ",
            "mimic_joint": "taccap_left_finger_joint",
            "mimic_gearing": -float(follower.get("multiplier", "1")),
            # "+ 0.0" normalises the -0.0 that negating a zero offset produces.
            "mimic_offset": -math.degrees(float(follower.get("offset", "0"))) + 0.0,
        },
        "drive": {
            "type": "force",
            "target_type": "position",
            "source": "config/mujoco.xml actuator/position[@joint='taccap_right_finger_joint']",
            "stiffness_nm_per_degree": float(position.get("kp")) * math.pi / 180,
            "damping_nm_s_per_degree": float(position.get("kv")) * math.pi / 180,
            "max_force_nm": float(limit.get("effort")),
            "status": "MuJoCo position gains converted per-radian to per-degree",
        },
        "mesh_layers": "usd/meshes/**/*.usdc",
        "shipped_layers_sha256": hash_tree(ASSETS, "usd"),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    with tempfile.TemporaryDirectory(prefix="taccap-usd-build-") as temporary:
        output = Path(temporary)
        generate_meshes(output)
        for mounted in (False, True):
            generate_model(output, mounted)
        expected = {ASSETS / "usd" / p.relative_to(output) for p in output.rglob("*.usd*")}
        stale = set((ASSETS / "usd").rglob("*.usd*")) - expected
        if args.check and stale:
            raise SystemExit(f"Stale USD layers: {sorted(stale)}")
        if not args.check:
            for path in stale:
                path.unlink()
        for source in sorted(output.rglob("*.usd*")):
            target = ASSETS / "usd" / source.relative_to(output)
            if args.check:
                if (
                    not target.is_file()
                    or Sdf.Layer.FindOrOpen(str(source)).ExportToString()
                    != Sdf.Layer.FindOrOpen(str(target)).ExportToString()
                ):
                    raise SystemExit(f"Regenerate stale USD: {target}")
            else:
                target.parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(source, target)
            print(target.relative_to(ASSETS))
    # Hash the shipped layers, so this runs after the copy above.
    config = update_config(
        ASSETS / "config" / "model.json", "usd", usd_metadata(), args.check
    )
    print(config.relative_to(ASSETS))


if __name__ == "__main__":
    main()
