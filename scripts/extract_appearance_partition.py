"""Extract the TacCap face-level material partition.

xensim-bench paints the gripper by triangle (black frame and motor, silver
structure, yellow fingertips and lens cap, grey finger covers, gel pad, lens).
That asset is the visual reference because it matches the physical gripper, but
it lives in another repository, so the partition is exported here as JSON and
regenerated by this script rather than needed at run time.

The source and this repository ship the same CAD. ``base_link`` matches face for
face (69 846 triangles, zero residual), so its partition transfers as an index
map. The finger meshes gained 180 triangles in the newer export, so those faces
are matched by centroid and the few unmatched ones take their nearest
neighbour's material.

The leaders' fingertips are the *follower's* fingertip solid rigidly placed in
another frame (identical vertex order, zero fit residual), so the leader finger
partition is the follower finger partition transferred after a Kabsch fit, with
the gel faces mapped to black: the leader has no tactile pad.

Run with an environment that has pxr, e.g.:

    /home/ubuntu/miniforge3/envs/xensim-bench/bin/python \
        scripts/extract_appearance_partition.py
"""

import json
import struct
import sys
from pathlib import Path

import numpy as np
from pxr import Usd, UsdGeom, UsdShade

ROOT = Path(__file__).resolve().parents[1]
BENCH = Path("/home/ubuntu/xensim-bench/assets/robots/rebot/rebot_taccap.usd")
SLAVE = ROOT / "ros/taccap_description/meshes"
MASTER = ROOT / "ros/taccap_master_description/meshes"

# key -> (shipped path relative to the package meshes dir, file)
SOURCES = {
    "base": ("slave/base_link.STL", SLAVE / "base_link.STL"),
    "left_finger": ("slave/grip_left.STL", SLAVE / "grip_left.STL"),
    "right_finger": ("slave/grip_right.STL", SLAVE / "grip_right.STL"),
}
BENCH_PRIMS = {
    "base": "/ReBot/right_gripper_taccap_g1_slave/base_visual",
    "left_finger": "/ReBot/right_gripper_grip_left/left_finger_visual",
    "right_finger": "/ReBot/right_gripper_grip_right/right_finger_visual",
}
MATERIAL_OF = {
    "Silver": "taccap_silver",
    "Cover": "taccap_cover",
    "Black": "taccap_black",
    "Yellow": "taccap_yellow",
    "Gel": "taccap_gel",
    "Lens": "taccap_lens",
}
# Leader finger meshes -> the follower finger they are the same part as.
MASTER_FINGERS = {
    "master/left/link1.STL": (MASTER / "left/link1.STL", "slave/grip_left.STL"),
    "master/left/link2.STL": (MASTER / "left/link2.STL", "slave/grip_left.STL"),
    "master/right/link1.STL": (MASTER / "right/link1.STL", "slave/grip_right.STL"),
    "master/right/link2.STL": (MASTER / "right/link2.STL", "slave/grip_right.STL"),
}
TIP_FACES = 2766
# Where the yellow rubber cap meets the black connector on every finger.
FINGERTIP_SEAM = {
    "axis": "x",
    "at": 0.1064,
    "material": "taccap_yellow",
    # Only the fingertip solid (the 2766-face cap) is recoloured. Screws, pins
    # and plates that cross the plane are separate solids and keep their colour.
    "component_faces": 2766,
    # The inner face is silicone/TPU rubber on both designs and stays dark: the
    # follower's gel pad and the leader's bare rubber pad and frame.
    "keep": ["taccap_gel"],
}


def stl_triangles(path):
    data = path.read_bytes()
    count = struct.unpack_from("<I", data, 80)[0]
    dtype = np.dtype([("normal", "<f4", 3), ("vertices", "<f4", (3, 3)), ("attr", "<u2")])
    triangles = np.frombuffer(data, dtype=dtype, offset=84, count=count)["vertices"]
    return triangles.astype(np.float64).reshape(-1, 3, 3), count


def bench_triangles(stage, path):
    prim = stage.GetPrimAtPath(path)
    mesh = UsdGeom.Mesh(prim)
    counts = np.array(mesh.GetFaceVertexCountsAttr().Get())
    if not np.all(counts == 3):
        raise ValueError(f"{path} is not triangulated")
    points = np.array(mesh.GetPointsAttr().Get(), dtype=np.float64)
    indices = np.array(mesh.GetFaceVertexIndicesAttr().Get())
    labels = np.full(len(counts), -1, dtype=np.int32)
    names = []
    for index, subset in enumerate(UsdShade.MaterialBindingAPI(prim).GetMaterialBindSubsets()):
        names.append(subset.GetPrim().GetName())
        labels[np.asarray(subset.GetIndicesAttr().Get(), dtype=np.int64)] = index
    return points[indices].reshape(-1, 3, 3), labels, names


def component_labels(triangles):
    """Per-face connected-component id (faces sharing a welded vertex)."""
    from scipy.sparse import coo_matrix
    from scipy.sparse.csgraph import connected_components

    points = triangles.reshape(-1, 3)
    welded = np.round(points * 1e6).astype(np.int64)
    _, inverse = np.unique(welded, axis=0, return_inverse=True)
    faces = inverse.reshape(-1, 3)
    count = len(faces)
    rows = np.concatenate([faces[:, 0], faces[:, 1], faces[:, 2]])
    columns = np.concatenate([faces[:, 1], faces[:, 2], faces[:, 0]])
    graph = coo_matrix((np.ones(len(rows)), (rows, columns)), shape=(count, count)).tocsr()
    _, labels = connected_components(graph, directed=False)
    return labels[faces[:, 0]]


def kabsch(source, target):
    """Rigid ``(R, t)`` with ``target ~ source @ R.T + t``."""
    source_centre, target_centre = source.mean(axis=0), target.mean(axis=0)
    covariance = (source - source_centre).T @ (target - target_centre)
    u, _, vt = np.linalg.svd(covariance)
    sign = np.sign(np.linalg.det(vt.T @ u.T))
    rotation = vt.T @ np.diag([1.0, 1.0, sign]) @ u.T
    return rotation, target_centre - source_centre @ rotation.T


def transfer_finger(reference_triangles, reference_labels, target_path):
    """Face labels for a leader finger mesh.

    The fingertip is the *same solid* as the follower's (identical vertex order,
    zero residual after a rigid fit), so those faces take the follower's labels
    with the gel mapped to black — the leader has no tactile pad. The rest of the
    finger is a different revision (several millimetres apart in places), so
    labelling it face by face would invent detail; its mechanical groups get one
    material each instead.
    """
    from scipy.spatial import cKDTree

    triangles, count = stl_triangles(target_path)
    reference_tip = _tip_component(reference_triangles)
    target_tip = _tip_component(triangles)
    reference_components = component_labels(reference_triangles)
    target_components = component_labels(triangles)

    points_reference = reference_triangles[reference_components == reference_tip].reshape(-1, 3)
    points_target = triangles[target_components == target_tip].reshape(-1, 3)
    if len(points_reference) != len(points_target):
        raise ValueError(f"{target_path.name}: fingertip vertex count differs")
    rotation, translation = kabsch(points_reference, points_target)

    tree = cKDTree(reference_triangles[reference_components == reference_tip].mean(axis=1))
    labels = np.full(count, "taccap_cover", dtype=object)
    tip_faces = target_components == target_tip
    # ``kabsch`` maps reference -> target, so invert it to bring target faces back.
    in_reference = (triangles[tip_faces].mean(axis=1) - translation) @ rotation
    distance, match = tree.query(in_reference, k=1)
    tip_labels = reference_labels[reference_components == reference_tip][match]
    tip_labels[tip_labels == "taccap_gel"] = "taccap_black"
    labels[tip_faces] = tip_labels
    if distance.max() > 1e-6:
        raise ValueError(f"{target_path.name}: fingertip fit residual {distance.max() * 1e3:.3f} mm")

    # Mechanical groups outside the tip, by triangle count and position.
    sizes = np.bincount(target_components)
    body = int(np.argmax(sizes))
    for component in np.unique(target_components):
        if component == target_tip or component == body:
            continue
        faces = target_components == component
        centre = triangles[faces].mean(axis=(0, 1)) * 1e3
        points = triangles[faces].reshape(-1, 3) * 1e3
        extent = points.max(axis=0) - points.min(axis=0)
        if abs(centre[0]) < 25 and sizes[component] > 3000:
            labels[faces] = "taccap_silver"      # hinge block
        elif np.allclose(sorted(extent), [5.5, 9.7, 10.0], atol=0.4):
            labels[faces] = "taccap_yellow"      # time-sync button on the outer side
        elif 60 < centre[0] < 85 and extent[0] > 25:
            labels[faces] = "taccap_cover"       # white side plate carrying the button
        else:
            labels[faces] = "taccap_black"       # screws and clip pins
    labels[target_components == body] = "taccap_cover"
    print(
        f"{target_path.name}: fingertips transferred from the follower "
        f"(median offset {np.median(distance) * 1e6:.1f} um), other groups by component"
    )
    return labels, count


def mirror_finger(labels, left, right, right_bench_labels):
    """Label the right finger from the mirrored left one, solid by solid.

    The fingers are mirror parts, but the two meshes are not exact mirrors, so a
    global nearest-face lookup lets faces cross into a neighbouring solid (grey
    cover landing on the black body, gel leaking off the pad). Each right solid
    is therefore paired with the mirrored left solid of the same face count and
    nearest centre, and faces are matched only inside that pair. A right solid
    with no left counterpart (the extra outer plate) keeps the bench labels.
    """
    from scipy.spatial import cKDTree

    mirror = np.array([1.0, -1.0, 1.0])
    left_solids = component_labels(left)
    right_solids = component_labels(right)
    left_centres = {
        int(s): (left[left_solids == s].reshape(-1, 3) * mirror).mean(axis=0)
        for s in np.unique(left_solids)
    }
    left_sizes = np.bincount(left_solids)
    result = right_bench_labels.copy()
    paired = 0
    for solid in np.unique(right_solids):
        faces = right_solids == solid
        centre = right[faces].reshape(-1, 3).mean(axis=0)
        size = int(faces.sum())
        # Same solid: similar size (the exports differ by a few percent) and
        # the closest mirrored centre.
        candidates = [
            s for s in left_centres
            if abs(left_sizes[s] - size) <= max(0.25 * size, 50)
        ]
        if not candidates:
            # No mirror partner: the small outer plate on this hand only.
            # It is white on the hardware.
            if 800 <= size <= 1000:
                result[faces] = "taccap_cover"
            continue
        best = min(candidates, key=lambda s: np.linalg.norm(left_centres[s] - centre))
        if np.linalg.norm(left_centres[best] - centre) > 0.005:
            continue
        source = left[left_solids == best] * mirror
        tree = cKDTree(source.mean(axis=1))
        _, match = tree.query(right[faces].mean(axis=1), k=1)
        result[faces] = labels[left_solids == best][match]
        paired += 1
    print(f"  right finger mirrored solid by solid: {paired} solids paired")
    return result


def _tip_component(triangles):
    """The fingertip is the 2 766-face solid present in every finger mesh."""
    sizes = np.bincount(component_labels(triangles))
    matches = np.where(sizes == TIP_FACES)[0]
    if len(matches) != 1:
        raise ValueError(f"expected one {TIP_FACES}-face fingertip, found {len(matches)}")
    return matches[0]


def encode(names, order):
    """Run-length encode ``names`` (strings) as ``[count, index, ...]``."""
    indices = [order.index(name) for name in names]
    runs = []
    start = 0
    for i in range(1, len(indices) + 1):
        if i == len(indices) or indices[i] != indices[start]:
            runs.extend([int(i - start), int(indices[start])])
            start = i
    return runs


def entry(labels, total, order, **extra):
    return {
        "faces": total,
        "materials": {name: int((np.asarray(labels) == name).sum()) for name in order},
        "order": order,
        "runs": encode(list(labels), order),
        **extra,
    }


# Camera window: glass, a black bezel ring, then the yellow surround ring
# (about 1.45x the glass radius on the hardware photo), then shell.
CAMERA_GLASS_M = 0.0085
CAMERA_BEZEL_M = 0.0096
CAMERA_RING_M = 0.0123
# Mesh origins of the body visuals (URDF visual origin).
BODY_ORIGIN = {
    "slave": np.array([0.01975, -0.0060769, 0.034023]),
    "master": np.array([0.02065, 0.0, 0.024785]),
}
CAMERA_BASE = np.array([-0.02285, 0.0, 0.04975])
BODY_ROTATION = np.array([[0.0, 0.0, -1.0], [0.0, 1.0, 0.0], [1.0, 0.0, 0.0]])


def camera_in_mesh_frame(model):
    """Camera position in the body mesh frame: mesh x is the optical axis."""
    return BODY_ROTATION.T @ (CAMERA_BASE - BODY_ORIGIN[model])


def camera_window_cut(model):
    """Cylinders that give the window an exact glass / bezel / ring edge.

    The bench asset paints the whole window yellow and the window is a triangle
    fan, so no per-face rule can produce the rings. The parts generator cuts the
    geometry instead. ``range`` bounds the cut along the axis: without it the
    infinite cylinder also lands on the body behind the window and paints a dark
    disc on the rear shell.
    """
    camera = camera_in_mesh_frame(model)
    return {
        "axis": "x",
        "centre": [float(camera[1]), float(camera[2])],
        "at": CAMERA_GLASS_M,
        "material": "taccap_lens",
        "bezel": {"at": CAMERA_BEZEL_M, "material": "taccap_black"},
        "range": [0.010, 10.0],
    }


# Status-LED window on the slave body: the 6.7 x 13.6 mm capsule on top of the
# shell (base frame centre about (-44.3, 0.1, 60.2) mm). Identified as a whole
# solid so its rim and lens are both translucent.
LIGHT_CENTRE_M = np.array([-0.0443, 0.0001, 0.0602])


def fix_light_window(triangles, labels, model, origin):
    """Make the indicator capsule translucent instead of yellow."""
    components = component_labels(triangles)
    centroids = triangles.mean(axis=1) @ BODY_ROTATION.T + origin
    light = np.zeros(len(triangles), dtype=bool)
    for component in np.unique(components):
        faces = components == component
        if faces.sum() > 2000:
            continue
        if np.linalg.norm(centroids[faces].mean(axis=0) - LIGHT_CENTRE_M) < 0.004:
            light |= faces
    labels = labels.copy()
    labels[light] = "taccap_light"
    print(f"  light window ({model}): {int(light.sum())} faces")
    return labels


def fix_camera_ring(triangles, labels, model):
    """Paint the bezel black, the surround ring yellow and the rest shell."""
    origin = BODY_ORIGIN[model]
    centroids = triangles.mean(axis=1) @ BODY_ROTATION.T + origin
    # camera_link has rpy 0, so the camera looks along base +Z.
    radius = np.hypot(centroids[:, 0] - CAMERA_BASE[0], centroids[:, 1] - CAMERA_BASE[1]) * 1e3
    height = centroids[:, 2] - CAMERA_BASE[2]
    near = (radius < 16.0) & (height > 0.005)
    bezel = near & (radius >= CAMERA_GLASS_M * 1e3) & (radius < CAMERA_BEZEL_M * 1e3)
    ring = near & (radius >= CAMERA_BEZEL_M * 1e3) & (radius < CAMERA_RING_M * 1e3)
    outside = near & (radius >= CAMERA_RING_M * 1e3)
    labels = labels.copy()
    labels[bezel] = "taccap_black"
    labels[ring] = "taccap_yellow"
    labels[outside] = "taccap_silver"
    print(
        f"  camera ({model}): {int(bezel.sum())} bezel, {int(ring.sum())} yellow ring, "
        f"{int(outside.sum())} shell"
    )
    return labels


def leader_body_partition(triangles):
    """Side buttons and their plates on the leaders, by connected component.

    The bench asset only covers the follower and the leader body is a different
    shape, so the groups are identified geometrically: on each side of the shell
    a round button sits at z ~8 mm with its plate directly above at z ~14 mm
    (mesh frame). The button is yellow on the hardware, the plate white.
    """
    components = component_labels(triangles)
    labels = np.full(len(triangles), "taccap_silver", dtype=object)
    groups = []
    for component in np.unique(components):
        faces = components == component
        if faces.sum() < 4000:
            continue
        points = triangles[faces].reshape(-1, 3) * 1e3
        centre = points.mean(axis=0)
        if abs(centre[1]) < 15.0:
            continue
        if 4.0 < centre[2] < 10.5:
            labels[faces] = "taccap_yellow"
            groups.append(("button", int(faces.sum()), np.round(centre, 1).tolist()))
        elif 12.0 < centre[2] < 17.0:
            labels[faces] = "taccap_cover"
            groups.append(("plate", int(faces.sum()), np.round(centre, 1).tolist()))
    print(f"  leader body: {groups}")
    return labels


def main():
    stage = Usd.Stage.Open(str(BENCH))
    partition = {}
    slave_labels = {}
    for key, prim_path in BENCH_PRIMS.items():
        relative, our_path = SOURCES[key]
        triangles, count = stl_triangles(our_path)
        bench, bench_labels, names = bench_triangles(stage, prim_path)
        tree = __import__("scipy.spatial", fromlist=["cKDTree"]).cKDTree(bench.mean(axis=1))
        distance, match = tree.query(triangles.mean(axis=1), k=1)
        labels = np.array([MATERIAL_OF[names[i]] for i in bench_labels[match]])
        exact = int((distance < 1e-9).sum())
        print(
            f"{relative}: {count} triangles, {exact} exact matches, "
            f"{count - exact} nearest-neighbour ({distance.max() * 1e3:.2f} mm max)"
        )
        order = [MATERIAL_OF[name] for name in names]
        extra = {"bench_faces": len(bench_labels), "bench_source": prim_path}
        if key == "base":
            order.append("taccap_light")
            labels = fix_camera_ring(triangles, labels, "slave")
            labels = fix_light_window(triangles, labels, "slave", BODY_ORIGIN["slave"])
            extra["radial_cut"] = camera_window_cut("slave")
        if key in ("left_finger", "right_finger"):
            extra["parting_plane"] = FINGERTIP_SEAM
        partition[relative] = entry(labels, count, order, **extra)
        slave_labels[relative] = (triangles, labels)

    # Symmetric fingers: mirror the left partition onto the right.
    left_triangles, left_labels = slave_labels["slave/grip_left.STL"]
    right_triangles, _ = slave_labels["slave/grip_right.STL"]
    right_bench = slave_labels["slave/grip_right.STL"][1]
    mirrored = mirror_finger(left_labels, left_triangles, right_triangles, right_bench)
    right_entry = partition["slave/grip_right.STL"]
    partition["slave/grip_right.STL"] = entry(
        mirrored,
        right_entry["faces"],
        right_entry["order"],
        bench_faces=right_entry["bench_faces"],
        bench_source=right_entry["bench_source"],
        parting_plane=FINGERTIP_SEAM,
        note="Mirrored from the left finger so both hands match the hardware.",
    )
    slave_labels["slave/grip_right.STL"] = (right_triangles, mirrored)

    for relative, (path, reference) in MASTER_FINGERS.items():
        triangles, labels = slave_labels[reference]
        target_labels, count = transfer_finger(triangles, labels, path)
        order = [name for name in ("taccap_cover", "taccap_silver", "taccap_black", "taccap_yellow")]
        partition[relative] = entry(
            target_labels,
            count,
            order,
            transferred_from=reference,
            parting_plane=FINGERTIP_SEAM,
            note="Leader finger: follower partition after a rigid fit, gel -> black.",
        )

    for side in ("left", "right"):
        relative = f"master/{side}/base_link.STL"
        path = MASTER / side / "base_link.STL"
        triangles, count = stl_triangles(path)
        labels = leader_body_partition(triangles)
        labels = fix_camera_ring(triangles, labels, "master")
        order = ["taccap_silver", "taccap_cover", "taccap_black", "taccap_yellow", "taccap_lens"]
        partition[relative] = entry(
            labels,
            count,
            order,
            radial_cut=camera_window_cut("master"),
            note="Leader body: side buttons yellow, their plates white, camera window "
            "glass/bezel/ring, rest silver.",
        )

    destination = ROOT / "ros/taccap_description/config/appearance.json"
    destination.write_text(
        json.dumps(
            {
                "source": "xensim-bench rebot_taccap.usd Looks/TacCap/*",
                "note": "Face-level material partition. Regenerate with "
                "scripts/extract_appearance_partition.py.",
                "partition": partition,
            },
            indent=2,
        )
        + "\n"
    )
    print(f"wrote {destination.relative_to(ROOT)}")


if __name__ == "__main__":
    sys.exit(main())
